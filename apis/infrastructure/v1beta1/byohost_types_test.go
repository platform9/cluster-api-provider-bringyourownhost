const byoHostCRDPath = "../../../config/crd/bases/infrastructure.cluster.x-k8s.io_byohosts.yaml"

// newByoHostSpecValidator builds a CEL validator for the spec schema of the
// generated ByoHost CRD, so the test evaluates the rules the API server runs
// and fails if the generated CRD is stale.
func newByoHostSpecValidator(t *testing.T) (*structuralcel.Validator, *schema.Structural) {
	t.Helper()

	data, err := os.ReadFile(byoHostCRDPath)
	require.NoError(t, err)

	crd := &apiextensionsv1.CustomResourceDefinition{}
	err = yaml.Unmarshal(data, crd)
	require.NoError(t, err)

	var specProps *apiextensionsv1.JSONSchemaProps
	for _, version := range crd.Spec.Versions {
		if version.Name != "v1beta1" {
			continue
		}
		require.NotNil(t, version.Schema)
		props, ok := version.Schema.OpenAPIV3Schema.Properties["spec"]
		require.True(t, ok, "v1beta1 schema has no spec property")
		specProps = &props
	}
	require.NotNil(t, specProps, "CRD has no v1beta1 version")

	internalProps := &apiextensionsinternal.JSONSchemaProps{}
	err = apiextensionsv1.Convert_v1_JSONSchemaProps_To_apiextensions_JSONSchemaProps(specProps, internalProps, nil)
	require.NoError(t, err)

	structural, err := schema.NewStructural(internalProps)
	require.NoError(t, err)

	validator := structuralcel.NewValidator(structural, false, celconfig.PerCallLimit)
	require.NotNil(t, validator, "ByoHost spec schema has no x-kubernetes-validations rules")
	return validator, structural
}

func TestByoHostSpec_IdentityImmutable(t *testing.T) {
	t.Parallel()

	const (
		identity      = "byoh:host:default:worker-1-abc12"
		otherIdentity = "byoh:host:default:worker-1-xyz89"
		wantMessage   = "identity is immutable"
	)

	testCases := []struct {
		name    string
		oldSpec map[string]any
		newSpec map[string]any
		wantErr bool
	}{
		{
			name:    "same identity with another field changed is allowed",
			oldSpec: map[string]any{"identity": identity},
			newSpec: map[string]any{
				"identity":     identity,
				"desiredAgent": map[string]any{"version": "v1.2.3"},
			},
		},
		{
			name:    "changed identity is rejected",
			oldSpec: map[string]any{"identity": identity},
			newSpec: map[string]any{"identity": otherIdentity},
			wantErr: true,
		},
		{
			name:    "removed identity is rejected",
			oldSpec: map[string]any{"identity": identity},
			newSpec: map[string]any{},
			wantErr: true,
		},
		{
			name:    "identity set after create is rejected",
			oldSpec: map[string]any{},
			newSpec: map[string]any{"identity": identity},
			wantErr: true,
		},
		{
			name:    "no identity before or after with another field changed is allowed",
			oldSpec: map[string]any{},
			newSpec: map[string]any{
				"desiredAgent": map[string]any{"version": "v1.2.3"},
			},
		},
	}

	validator, structural := newByoHostSpecValidator(t)

	for _, tc := range testCases {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()

			errs, _ := validator.Validate(
				t.Context(),
				field.NewPath("spec"),
				structural,
				tc.newSpec,
				tc.oldSpec,
				celconfig.RuntimeCELCostBudget,
			)

			if !tc.wantErr {
				assert.Empty(t, errs)
				return
			}
			require.Len(t, errs, 1)
			assert.Contains(t, errs[0].Error(), wantMessage)
		})
	}
}
